function nest(x, y, w, h, vw, vh, inner, vx = 0, vy = 0) {
  return `<svg x="${x}" y="${y}" width="${w}" height="${h}" viewBox="${vx} ${vy} ${vw} ${vh}" overflow="visible">${inner}</svg>`;
}
function ribbonText(w, h, label) {
  return `<text x="${w / 2}" y="${(h * 0.39 + h * 0.15).toFixed(1)}" text-anchor="middle" font-family="Lilita One, sans-serif" font-size="${(h * 0.42).toFixed(1)}" fill="#fff6df" stroke="${P.lacquerInk}" stroke-width="5" stroke-linejoin="round" paint-order="stroke" letter-spacing="2">${label}</text>`;
}
function modalDoc(w, h, variant, title, rw = 520, rh = 84) {
  const inner = panelMarkup(w, h, variant)
    + `<g transform="translate(${(w - rw) / 2} -44)">${ribbonMarkup(rw, rh)}${ribbonText(rw, rh, title)}</g>`;
  return svgDoc(-16, -60, w + 32, h + 80, inner, `width="${w + 32}" height="${h + 80}"`);
}


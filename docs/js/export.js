/* ---------- Font embedding ---------- */
const FONT_CSS_URL = 'https://fonts.googleapis.com/css2?family=Lilita+One&family=Nunito:wght@800;900&display=swap';
let fontPromise = null;
function toBase64(buf) {
  const bytes = new Uint8Array(buf);
  let bin = '';
  for (let i = 0; i < bytes.length; i += 0x8000) bin += String.fromCharCode.apply(null, bytes.subarray(i, i + 0x8000));
  return btoa(bin);
}
/** @font-face rules with the Latin subsets inlined as data URIs (cached). */
export function embeddedFontCSS() {
  if (!fontPromise) {
    fontPromise = (async () => {
      try {
        const css = await (await fetch(FONT_CSS_URL)).text();
        let out = '';
        for (const block of css.split('@font-face').slice(1)) {
          const range = /unicode-range:\s*([^;]+);/.exec(block);
          if (range && !/U\+0000-00FF/i.test(range[1])) continue;
          const url = /url\(([^)]+)\)/.exec(block);
          const fam = /font-family:\s*([^;]+);/.exec(block);
          const wt = /font-weight:\s*([^;]+);/.exec(block);
          if (!url || !fam) continue;
          const buf = await (await fetch(url[1].replace(/['"]/g, ''))).arrayBuffer();
          out += `@font-face{font-family:${fam[1]};font-style:normal;font-weight:${wt ? wt[1] : 400};src:url(data:font/woff2;base64,${toBase64(buf)}) format('woff2');}`;
        }
        return out;
      } catch (e) {
        console.warn('Font embedding unavailable, exports will use fallback fonts.', e);
        return '';
      }
    })();
  }
  return fontPromise;
}
const hasText = (svg) => /<text[\s>]/.test(svg);
export async function withFonts(svg) {
  if (!hasText(svg)) return svg;
  const css = await embeddedFontCSS();
  if (!css) return svg;
  return svg.replace(/<svg\b[^>]*>/, (m) => `${m}<style>${css}</style>`);
}

/* ---------- Rasterising ---------- */
function rootTag(svg) { return /<svg\b[^>]*>/.exec(svg)[0]; }
export function svgSize(svg) {
  const tag = rootTag(svg);
  const w = /\swidth="([\d.]+)"/.exec(tag), h = /\sheight="([\d.]+)"/.exec(tag);
  if (w && h) return { w: +w[1], h: +h[1] };
  const vb = /viewBox="([^"]+)"/.exec(tag)[1].split(/[\s,]+/).map(Number);
  return { w: vb[2], h: vb[3] };
}
function setSize(svg, w, h) {
  const tag = rootTag(svg);
  const clean = tag.replace(/\s(width|height)="[^"]*"/g, '');
  return svg.replace(tag, clean.replace('<svg', `<svg width="${w}" height="${h}"`));
}

/** Render an SVG document to a PNG blob at `scale`× its intrinsic size. */
export async function svgToPng(svg, scale = 2) {
  const { w, h } = svgSize(svg);
  const W = Math.round(w * scale), H = Math.round(h * scale);
  const doc = setSize(await withFonts(svg), W, H);
  const url = URL.createObjectURL(new Blob([doc], { type: 'image/svg+xml;charset=utf-8' }));
  try {
    const img = new Image();
    await new Promise((res, rej) => { img.onload = res; img.onerror = rej; img.src = url; });
    if (img.decode) await img.decode().catch(() => {});
    await wait(40); // give embedded fonts a beat
    const canvas = document.createElement('canvas');
    canvas.width = W;
    canvas.height = H;
    canvas.getContext('2d').drawImage(img, 0, 0, W, H);
    return await new Promise((res) => canvas.toBlob(res, 'image/png'));
  } finally {
    URL.revokeObjectURL(url);
  }
}

export function saveBlob(blob, name) {
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = name;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(a.href), 4000);
}


/* ==========================================================
   Sheet page
   ========================================================== */
export function buildSheet(root) {
  const sections = catalogue();
  const all = sections.flatMap((s) => s.items.map((it) => ({ ...it, section: s.id })));
  root.innerHTML = sections.map((s) => `
    <section class="sheet-section" id="sec-${s.id}">
      <header class="sec-head"><h2>${s.title}</h2><p>${s.note}</p><span class="count">${s.items.length} item${s.items.length > 1 ? 's' : ''}</span></header>
      <div class="sheet-grid${s.id === 'tiles' ? ' tiles-grid' : ''}">
        ${s.items.map((it) => {
          const { w, h } = svgSize(it.svg);
          const key = `${s.id}/${it.name}`;
          return `<article class="asset${it.wide ? ' wide' : ''}${it.small ? ' small' : ''}" data-key="${key}">
            <div class="preview${it.dark ? ' dark' : ''}${it.scene ? ' scene' : ''}">${it.svg}</div>
            <div class="meta"><h3>${it.label}</h3><span>${Math.round(w)} × ${Math.round(h)}</span></div>
            <div class="actions"><button class="dl" data-fmt="png">PNG 2×</button><button class="dl ghost" data-fmt="svg">SVG</button></div>
          </article>`;
        }).join('')}
      </div>
    </section>`).join('');

  const byKey = new Map(all.map((it) => [`${it.section}/${it.name}`, it]));
  root.addEventListener('click', async (e) => {
    const btn = e.target.closest('button.dl');
    if (!btn) return;
    const item = byKey.get(btn.closest('.asset').dataset.key);
    const old = btn.textContent;
    btn.disabled = true;
    btn.textContent = '…';
    try {
      if (btn.dataset.fmt === 'png') saveBlob(await svgToPng(item.svg, 2), `${item.name}@2x.png`);
      else saveBlob(new Blob([await withFonts(item.svg)], { type: 'image/svg+xml' }), `${item.name}.svg`);
    } catch (err) {
      console.error(err);
      alert('Sorry — that export failed in this browser.');
    } finally {
      btn.disabled = false;
      btn.textContent = old;
    }
  });

  const zipBtn = document.getElementById('zip-all');
  const status = document.getElementById('zip-status');
  if (zipBtn) zipBtn.addEventListener('click', async () => {
    if (!window.JSZip) { status.textContent = 'JSZip could not load — check your connection.'; return; }
    zipBtn.disabled = true;
    const zip = new window.JSZip();
    try {
      let i = 0;
      for (const it of all) {
        i++;
        status.textContent = `Rendering ${i} / ${all.length} — ${it.label}`;
        const png = await svgToPng(it.svg, 2);
        zip.file(`png/${it.section}/${it.name}@2x.png`, png);
        zip.file(`svg/${it.section}/${it.name}.svg`, await withFonts(it.svg));
      }
      status.textContent = 'Compressing…';
      const blob = await zip.generateAsync({ type: 'blob', compression: 'DEFLATE', compressionOptions: { level: 6 } });
      saveBlob(blob, 'mahjong-connect-art.zip');
      status.textContent = `Done — ${all.length} assets, PNG + SVG.`;
    } catch (err) {
      console.error(err);
      status.textContent = 'Export failed — see console for details.';
    } finally {
      zipBtn.disabled = false;
    }
  });
  return all.length;
}
